const selector = document.querySelector('#language-select');
const label = selector.closest('.language-control');

function applyLanguage(language) {
    const english = language === 'en';
    document.documentElement.lang = language;
    selector.value = language;
    label.querySelector('span').textContent = english ? 'Language' : 'Idioma';
    document.querySelectorAll('[data-i18n]').forEach(element => {
        element.textContent = translations[element.dataset.i18n][english ? 1 : 0];
    });
    document.querySelector('#inicio img').alt = english ? 'Portrait of Marco Antonio' : 'Retrato de Marco Antonio';
    const email = document.querySelector('#contact a[href^="mailto:"]');
    if (email) email.setAttribute('aria-label', english ? 'Email' : 'Correo electrónico');
    if (document.readyState === 'complete') startTypewriter(language);
    if (window.AOS) requestAnimationFrame(() => window.AOS.refresh());
}

let initialLanguage = 'es';
try {
    if (localStorage.getItem('portfolio-language') === 'en') initialLanguage = 'en';
} catch {}
applyLanguage(initialLanguage);
label.hidden = false;

selector.addEventListener('change', () => {
    applyLanguage(selector.value);
    try {
        localStorage.setItem('portfolio-language', selector.value);
    } catch {}
});
